#!/usr/bin/env python3
"""Generate Zig and Rust Typed Neuron wire DTOs from one checked-in schema."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "schema/typed-neuron-wire.json"
ZIG_PATH = ROOT / "src/generated_wire.zig"
RUST_PATH = (
    ROOT.parent
    / "aiko/crates/codegen/xai-grok-shell/src/contract_native/typed_neuron_wire.rs"
)
PIN_PATH = ROOT.parent / "contract/libcontract/typed-neuron.lock.json"

ZIG_TYPES = {
    "string": "[]const u8",
    "bool": "bool",
    "u16": "u16",
    "u32": "u32",
    "u64": "u64",
    "optional_string": "?[]const u8",
    "optional_u64": "?u64",
    "list_string": "[]const []const u8",
}

RUST_TYPES = {
    "string": "String",
    "bool": "bool",
    "u16": "u16",
    "u32": "u32",
    "u64": "u64",
    "optional_string": "Option<String>",
    "optional_u64": "Option<u64>",
    "list_string": "Vec<String>",
}


def canonical_schema(schema: dict[str, Any]) -> bytes:
    return json.dumps(schema, sort_keys=True, separators=(",", ":")).encode()


def zig_type(field: dict[str, Any]) -> str:
    kind = field["kind"]
    if kind == "type":
        return field["item"]
    if kind == "list_type":
        return f"[]const {field['item']}"
    return ZIG_TYPES[kind]


def rust_type(field: dict[str, Any]) -> str:
    kind = field["kind"]
    if kind == "type":
        return field["item"]
    if kind == "list_type":
        return f"Vec<{field['item']}>"
    return RUST_TYPES[kind]


def zig_default(field: dict[str, Any]) -> str:
    if "default" not in field:
        return ""
    value = field["default"]
    if value is None:
        return " = null"
    if value == []:
        return " = &.{}"
    if isinstance(value, bool):
        return f" = {'true' if value else 'false'}"
    if isinstance(value, int):
        return f" = {value}"
    if isinstance(value, str):
        return f' = "{value}"'
    raise ValueError(f"unsupported Zig default: {value!r}")


def rust_default_attr(field: dict[str, Any]) -> list[str]:
    if "default" not in field:
        return []
    value = field["default"]
    attrs = ["    #[serde(default"]
    if value is True:
        attrs[0] += ' = "default_true"'
    elif value == 1000:
        attrs[0] += ' = "default_confidence"'
    attrs[0] += ")]"
    return attrs


def package_digest(schema_bytes: bytes) -> tuple[str, list[str]]:
    relative_paths = [
        "tools/generate_wire_bindings.py",
        "src/wire.zig",
        "src/runtime.zig",
        "src/types.zig",
        "src/caps.zig",
    ]
    hasher = hashlib.sha256()
    for name, content in [
        ("schema/typed-neuron-wire.json", schema_bytes),
        *((name, (ROOT / name).read_bytes()) for name in relative_paths),
    ]:
        encoded_name = name.encode()
        hasher.update(len(encoded_name).to_bytes(8, "big"))
        hasher.update(encoded_name)
        hasher.update(len(content).to_bytes(8, "big"))
        hasher.update(content)
    return hasher.hexdigest(), ["schema/typed-neuron-wire.json", *relative_paths]


def render_zig(schema: dict[str, Any], digest: str, package: str) -> str:
    lines = [
        "//! @generated by tools/generate_wire_bindings.py; DO NOT EDIT.",
        f'pub const SOURCE_SCHEMA = "{schema["source_schema"]}";',
        f'pub const CORE_VERSION = "{schema["core_version"]}";',
        f'pub const HASH_PROFILE = "{schema["hash_profile"]}";',
        f'pub const SCHEMA_DIGEST = "{digest}";',
        f'pub const PACKAGE_DIGEST = "{package}";',
    ]
    for name, value in schema["constants"].items():
        lines.append(f'pub const {name} = "{value}";')
    lines.append("")
    for enum in schema["enums"]:
        lines.append(f"pub const {enum['name']} = enum {{")
        lines.extend(f"    {value}," for value in enum["values"])
        lines.append("};")
        lines.append("")
    for item in schema["types"]:
        lines.append(f"pub const {item['name']} = struct {{")
        for field in item["fields"]:
            lines.append(
                f"    {field['name']}: {zig_type(field)}{zig_default(field)},"
            )
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def render_rust(schema: dict[str, Any], digest: str, package: str) -> str:
    lines = [
        "// @generated by neuron/tools/generate_wire_bindings.py; DO NOT EDIT.",
        "use serde::{Deserialize, Serialize};",
        "",
        "#[allow(dead_code)]",
        "fn default_true() -> bool {",
        "    true",
        "}",
        "#[allow(dead_code)]",
        "fn default_confidence() -> u16 {",
        "    1000",
        "}",
        "",
        f'pub(crate) const CORE_VERSION: &str = "{schema["core_version"]}";',
        f'pub(crate) const HASH_PROFILE: &str = "{schema["hash_profile"]}";',
        "pub(crate) const SCHEMA_DIGEST: &str =",
        f'    "{digest}";',
        "pub(crate) const PACKAGE_DIGEST: &str =",
        f'    "{package}";',
    ]
    for name, value in schema["constants"].items():
        declaration = f'pub(crate) const {name}: &str = "{value}";'
        if len(declaration) > 100:
            lines.extend(
                [f"pub(crate) const {name}: &str =", f'    "{value}";']
            )
        else:
            lines.append(declaration)
    lines.append("")
    for enum in schema["enums"]:
        lines.extend(
            [
                "#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]",
                '#[serde(rename_all = "snake_case")]',
                f"pub enum {enum['name']} {{",
            ]
        )
        lines.extend(f"    {value.title()}," for value in enum["values"])
        lines.append("}")
        lines.append("")
    for item in schema["types"]:
        lines.extend(
            [
                "#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]",
                "#[serde(deny_unknown_fields)]",
                f"pub struct {item['name']} {{",
            ]
        )
        for field in item["fields"]:
            lines.extend(rust_default_attr(field))
            lines.append(f"    pub {field['name']}: {rust_type(field)},")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def render_pin(
    schema: dict[str, Any], digest: str, package: str, package_files: list[str]
) -> str:
    # Source is now configurable for published git deps (Option A / ROADMAP R5).
    # Default keeps the historical sibling layout for dev.
    # Override with env var TYPED_NEURON_SOURCE when emitting for a git-based checkout.
    # Example:
    #   TYPED_NEURON_SOURCE='git+ssh://git@100.67.11.99:2222/Unbrowse/neuron.git#1e69ca97...' \
    #   python3 tools/generate_wire_bindings.py
    source = os.environ.get("TYPED_NEURON_SOURCE", "../../neuron")
    return (
        json.dumps(
            {
                "package": schema["package"],
                "core_version": schema["core_version"],
                "package_digest": package,
                "package_digest_algorithm": "sha256-framed-files/v1",
                "package_files": package_files,
                "schema_digest": digest,
                "source": source,
                "source_schema": schema["source_schema"],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )


def outputs() -> dict[Path, str]:
    schema = json.loads(SCHEMA_PATH.read_text())
    schema_bytes = canonical_schema(schema)
    digest = hashlib.sha256(schema_bytes).hexdigest()
    package, package_files = package_digest(schema_bytes)
    return {
        ZIG_PATH: render_zig(schema, digest, package),
        RUST_PATH: render_rust(schema, digest, package),
        PIN_PATH: render_pin(schema, digest, package, package_files),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale: list[Path] = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(path)
    if stale:
        for path in stale:
            print(f"stale generated binding: {path}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
