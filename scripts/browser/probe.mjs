import { chromium, devices } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['iPhone 14 Pro'] });
const page = await ctx.newPage();
await page.goto('https://sauros.lewis-6d8.workers.dev/quote/NVDA', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(10000);
const body = await page.locator('body').innerText();
const idx = body.indexOf('β');
console.log('β index:', idx);
if (idx >= 0) console.log('around β:', JSON.stringify(body.slice(idx, idx+30)));
console.log('full kpi region:', JSON.stringify(body.slice(body.indexOf('P/E (TTM)'), body.indexOf('P/E (TTM)') + 300)));
await browser.close();
