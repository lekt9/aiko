const batch=(sequence=1):BrowserEventBatch=>({schema:BROWSER_EVENT_SCHEMA,producer:producer().producer,epoch:producer().epoch,generation:1,items:[{sequence,occurrence:`occurrence-${sequence}`,kind:"push",observedAt:now,sourceId:"source-event",fields:{origin:"https://example.com",outcome:"received"},payload:{body:"PRIVATE_BROWSER_PUSH_5521"}}]});
