test("Bun receive-only browser ingress drives checked native source once across disk restart",async()=>{
  let g=producer();const f=await fixture(true,{defaults:true,overrides:{logSources:()=>[source()],browserProducers:()=>[g]}});
  await f.run(setup);
  const models=f.models();
  expect((await f.raw(request(batch(),"0".repeat(64)))).status).toBe(401);
  expect((await f.raw(request(batch()))).status).toBe(202);
  await f.drive();
  const rows=await f.events();
  expect(rows.filter(e=>e.type==="AikoBrowserPushObserved")).toHaveLength(1);
  expect(rows.filter(e=>e.type==="AikoChannelLogSourceProgress"&&e.disposition==="accepted")).toHaveLength(1);
  expect(rows.some(e=>e.type==="AikoChannelWiringAccepted"&&e.replyTo)).toBe(true);
  expect(JSON.stringify(rows)).not.toContain("PRIVATE_BROWSER_PUSH_5521");
  const runs=rows.filter(e=>e.type==="AikoHarnessRunStarted").length;
  await f.restart();
  expect((await f.raw(request(batch()))).status).toBe(202);await f.drive();
  expect((await f.events()).filter(e=>e.type==="AikoHarnessRunStarted")).toHaveLength(runs);
  expect(f.models()).toBe(models);
  g={...g,active:false};expect((await f.raw(request(batch(2)))).status).toBe(403);
});
