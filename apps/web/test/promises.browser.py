# Run via browser-harness with an isolated profile/CDP URL and no cookie seeding.
import os, pathlib, json
root = pathlib.Path(os.environ['UNLOCK_ROOT'])
exec((root / 'scripts/browser_helpers.py').read_text().replace("OUT = ROOT / 'artifacts/vault-qa'", "OUT = ROOT / 'artifacts/recovery-promises-20260908'"))
BASE = os.environ.get('PROMISES_BASE_URL', 'http://127.0.0.1:42817')
try:
    new_tab(BASE); wait_for_load()
    wait('!!window.promiseFixture && document.body.innerText.includes("Review promises (1)")')
    fill('Unrelated draft', 'Keep this unsent work')
    assert not js('document.body.innerText.includes("Send the reviewed summary")')
    click('button', 'Review promises (1)')
    click('DisclosureTriangle', 'Review frozen source and final inputs')
    assert js('document.body.innerText.includes("Final ThinkFeel summary")')
    assert js('document.body.innerText.includes("Synthetic recipient")')
    viewport(360, 800); no_overflow(); audit('promises-review-mobile'); shot('promises-review-mobile')
    viewport(1024, 900)
    js('promiseFixture.holdDecision=true;promiseFixture.holdRead=true;promiseFixture.before=promiseFixture.reads;true')
    wait('promiseFixture.reads>promiseFixture.before')
    click('button', 'Approve this task')
    click('button', 'Replace callback')
    click('button', 'Move review')
    assert js('promiseFixture.decisions.length') == 1
    assert js('document.querySelector("textarea").value') == 'Keep this unsent work'
    assert js('document.querySelector("section button").disabled')
    js('promiseFixture.releaseDecision();true')
    wait('document.body.innerText.includes("Review promises (0)")')
    js('promiseFixture.releaseRead();promiseFixture.holdRead=false;promiseFixture.holdDecision=false;true')
    assert not js('Array.from(document.querySelectorAll("button")).some(b=>b.textContent==="Approve this task")')
    assert js('JSON.stringify(promiseFixture.decisions[0])') == '{"id":"promise-fixture","hash":"' + 'a'*64 + '","decision":"approve"}'
    record('Exact frozen payload review; single owner decision survives callback churn and stale poll without replacing drafts')
    js('promiseFixture.rows[0].state="unknown";true')
    click('button', 'Refresh tasks')
    wait('document.body.innerText.includes("Outcome unconfirmed")')
    assert not js('Array.from(document.querySelectorAll("section button")).some(b=>b.textContent.includes("Approve")||b.textContent.includes("Cancel"))')
    assert js('document.body.innerText.includes("No automatic retry")')
    record('Unknown writes have truthful status and no retry/approval controls')
    js('promiseFixture.readStatus=503;true'); click('button', 'Refresh tasks')
    wait('document.body.innerText.includes("Could not refresh tasks")')
    assert js('document.body.innerText.includes("Send the reviewed summary")')
    js('promiseFixture.readStatus=403;true'); click('button', 'Refresh tasks')
    wait('document.body.innerText.includes("Your access changed")')
    assert not js('document.body.innerText.includes("Final ThinkFeel summary")')
    assert not js('document.body.innerText.includes("Send the reviewed summary")')
    record('Transient errors retain review; denied reads clear protected source and inputs')
    js('promiseFixture.readStatus=200;promiseFixture.rows[0].state="pending";true')
    click('button', 'Refresh tasks'); wait('document.body.innerText.includes("Review promises (1)")')
    js('promiseFixture.failDecision=true;true'); click('button', 'Approve this task')
    wait('document.body.innerText.includes("Could not confirm your decision")')
    assert js('Array.from(document.querySelectorAll("button")).find(b=>b.textContent==="Approve this task").disabled')
    assert js('promiseFixture.decisions.length') == 2
    js('promiseFixture.failDecision=false;true'); click('button', 'Refresh tasks')
    wait('!Array.from(document.querySelectorAll("button")).find(b=>b.textContent==="Approve this task").disabled')
    record('Lost decision acknowledgement requires read reconciliation, never automatic resubmission')
    click('button', 'Decline')
    wait('document.body.innerText.includes("Declined")')
    wait('document.activeElement.tagName==="H3" && document.activeElement.textContent==="Promises"')
    record('Settled decisions restore focus when the clicked control disappears')
    js('promiseFixture.holdRead=true;promiseFixture.before=promiseFixture.reads;true')
    click('button', 'Refresh tasks'); wait('promiseFixture.reads>promiseFixture.before')
    js('promiseFixture.oldRead=promiseFixture.releaseRead;promiseFixture.rows=[];promiseFixture.holdRead=false;true')
    click('button', 'Switch account'); wait('document.body.innerText.includes("No tasks to review")')
    js('promiseFixture.oldRead();true')
    assert not js('document.body.innerText.includes("Send the reviewed summary")')
    assert js('document.querySelector("textarea").value') == ''
    record('Account replacement immediately clears private review and fences old in-flight reads')
    viewport(360, 800); no_overflow(); audit('promises-empty-mobile')
    record('Mobile empty-state layout and automated accessibility scan pass')
    (OUT / 'browser-results.json').write_text(json.dumps({'passed':len(results),'failed':0,'checks':results}, indent=2))
except Exception:
    (OUT / 'browser-results.json').write_text(json.dumps({'passed':len(results),'failed':1,'checks':results}, indent=2))
    raise
finally:
    close_tab()
