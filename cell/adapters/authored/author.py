#!/usr/bin/env python3
"""Digest-gated authoring for a bounded family of Cell adapters.

The author sees promoted boundary shape and an opaque credential contract.  It
never receives a capability gap: a fixed catalogue chooses real transforms from
source schema alone.  Generated bytes remain inert until a behavior receipt is
pinned, admitted, and attached with their exact declared authority.
"""
from __future__ import annotations
import argparse, hashlib, json, os, pathlib, py_compile, subprocess, sys, time

class Refusal(Exception): pass

def canon(value): return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
def sha(value): return hashlib.sha256(value if isinstance(value, bytes) else canon(value)).hexdigest()
def read(path):
    try: return json.loads(pathlib.Path(path).read_text())
    except (OSError, json.JSONDecodeError) as exc: raise Refusal(f"invalid contract: {path}") from exc
def atomic(path, value):
    path=pathlib.Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    tmp=path.with_suffix(path.suffix+".tmp"); tmp.write_text(json.dumps(value,sort_keys=True,indent=2)+"\n")
    os.chmod(tmp,0o600); os.replace(tmp,path)
def package_digest(package):
    h=hashlib.sha256()
    for p in sorted(pathlib.Path(package).rglob("*")):
        if p.is_file() and "__pycache__" not in p.parts and not p.name.endswith((".pyc",".tmp")):
            rel=str(p.relative_to(package)).encode(); data=p.read_bytes()
            h.update(len(rel).to_bytes(4,"big")); h.update(rel); h.update(len(data).to_bytes(8,"big")); h.update(data)
    return h.hexdigest()

def contracts(boundary_path, credential_path):
    boundary, credential=read(boundary_path),read(credential_path)
    if boundary.get("schema") != "aiko.unbrowse-boundary/v1" or boundary.get("status") != "promoted":
        raise Refusal("authoring requires a promoted declared boundary")
    promotion=boundary.get("promotion") or {}
    if not promotion.get("independent") or promotion.get("basis") != "observation_and_independent_replay_agreement":
        raise Refusal("declared boundary lacks independent replay evidence")
    handle=((boundary.get("auth") or {}).get("credential_handle"))
    if not isinstance(handle,str) or not handle.startswith("cred:") or credential.get("handle") != handle:
        raise Refusal("opaque credential handle does not match boundary")
    if credential.get("status","active") != "active" or credential.get("revoked") is True:
        raise Refusal("credential contract is not active")
    if int(credential.get("expires_at",0)) <= int(time.time()): raise Refusal("credential contract expired")
    if "observe" not in credential.get("allowed_actions",[]): raise Refusal("credential lacks observe authority")
    return boundary,credential

# TRANSFORM_CATALOG_BEGIN
# Catalogue entries inspect only a pinned response schema.  They are deliberately
# boring: bounded structural predicates select code written before any request.
def worker_directory_matches(schema):
    try:
        workers=schema["fields"]["workers"]
        item=workers["items"][0]
        return (schema["type"]=="object" and workers["type"]=="array" and
                item["type"]=="object" and item["fields"]["id"]["type"]=="integer")
    except (KeyError,IndexError,TypeError): return False

CATALOG=(
    ("worker-directory/v1", worker_directory_matches),
)
# TRANSFORM_CATALOG_END

def audit_catalog(source_path=None):
    source=pathlib.Path(source_path or __file__).read_text()
    try: block=source.split("# TRANSFORM_CATALOG_BEGIN",1)[1].split("# TRANSFORM_CATALOG_END",1)[0]
    except IndexError as exc: raise Refusal("transform catalogue markers missing") from exc
    banned=(("expect"+"_"+"contains"), ("accept"+"ance"), "gap[", "gap.get", "args.gap")
    if any(token in block for token in banned):
        raise Refusal("transform catalogue reads gap criteria")
    return True

ADAPTER=r'''#!/usr/bin/env python3
import argparse,json,subprocess,sys
p=argparse.ArgumentParser(); p.add_argument("--port",required=True); p.add_argument("--boundary",required=True)
p.add_argument("--url",required=True); p.add_argument("--credential-env",required=True); a=p.parse_args()
r=subprocess.run([sys.executable,a.port,"execute",a.boundary,a.url,"--credential-env",a.credential_env],capture_output=True)
if r.returncode: sys.stderr.buffer.write(r.stderr); raise SystemExit(r.returncode)
try: product=json.loads(r.stdout); workers=product["workers"]
except (ValueError,KeyError,TypeError): print("refused: invalid worker directory",file=sys.stderr); raise SystemExit(2)
if not isinstance(workers,list) or any(not isinstance(w,dict) or type(w.get("id")) is not int for w in workers):
    print("refused: invalid worker directory",file=sys.stderr); raise SystemExit(2)
print(json.dumps({"family":"worker-directory/v1","worker_ids":[w["id"] for w in workers]},sort_keys=True,separators=(",",":")))
'''

def paths(work):
    w=pathlib.Path(work); package=w/"packages"/"worker-directory"
    return w,package,w/"receipts",w/"registry",w/"attachments"

def cmd_author(a):
    audit_catalog()
    boundary,credential=contracts(a.boundary,a.credential_contract)
    schema=boundary["observation"]["response_schema"]
    matches=[name for name,pred in CATALOG if pred(schema)]
    if matches != ["worker-directory/v1"]: raise Refusal("no unique bounded transform for boundary schema")
    w,package,receipts,registry,attachments=paths(a.work)
    if any(x.exists() for x in (receipts,registry,attachments)): raise Refusal("authoring workspace already has retained authority")
    package.mkdir(parents=True,exist_ok=True)
    adapter=package/"adapter.py"; adapter.write_text(ADAPTER); os.chmod(adapter,0o700)
    authority={"actions":["observe"],"credential_handles":[credential["handle"]],
               "network_origins":[boundary["route"]["authority"]],"write_prefixes":[]}
    atomic(package/"manifest.json",{"schema":"aiko.authored-adapter/v1","family":matches[0],
           "entrypoint":"adapter.py","authority":authority,"provenance":{"boundary_digest":sha(boundary)}})
    print(json.dumps({"state":"authored-inert","package":str(package),"digest":package_digest(package)}))

def invoke(a, package):
    return subprocess.run([sys.executable,str(package/"adapter.py"),"--port",a.port,"--boundary",a.boundary_state,
        "--url",a.url,"--credential-env",a.credential_env],capture_output=True,text=True)

def cmd_compile(a):
    _,package,_,registry,attachments=paths(a.work)
    py_compile.compile(str(package/"adapter.py"),doraise=True)
    if registry.exists() or attachments.exists(): raise Refusal("compilation retained admission or authority")
    print(json.dumps({"compiled":True,"retained":False}))

def cmd_test(a):
    _,package,receipts,registry,attachments=paths(a.work)
    if registry.exists() or attachments.exists(): raise Refusal("behavior test must precede admission and attachment")
    before=package_digest(package); result=invoke(a,package)
    if result.returncode: raise Refusal("real behavior test failed: "+result.stderr.strip())
    try: product=json.loads(result.stdout)
    except json.JSONDecodeError as exc: raise Refusal("adapter emitted invalid JSON") from exc
    if product != {"family":"worker-directory/v1","worker_ids":[a.expected_worker_id]}:
        raise Refusal("real behavior product did not satisfy fixed family contract")
    after=package_digest(package)
    if before != after: raise Refusal("package mutated while tested")
    atomic(receipts/"behavior.json",{"schema":"aiko.adapter-behavior/v1","package_digest":before,
           "real_path":"unbrowse.execute","product_digest":sha(product),"passed":True})
    print(json.dumps({"tested":True,"package_digest":before,"product":product}))

def cmd_admit(a):
    _,package,receipts,registry,attachments=paths(a.work)
    if attachments.exists(): raise Refusal("cannot admit after attachment")
    behavior=read(receipts/"behavior.json"); digest=package_digest(package)
    if behavior.get("passed") is not True or behavior.get("package_digest") != digest:
        raise Refusal("current bytes lack a matching behavior receipt")
    manifest=read(package/"manifest.json")
    admission={"schema":"aiko.adapter-admission/v1","package_digest":digest,"family":manifest["family"],
               "behavior_receipt_digest":sha(behavior),"authority_granted":False}
    atomic(registry/(digest+".json"),admission)
    print(json.dumps(admission,sort_keys=True))

def cmd_attach(a):
    boundary,credential=contracts(a.boundary,a.credential_contract)
    _,package,receipts,registry,attachments=paths(a.work); digest=package_digest(package)
    admission=read(registry/(digest+".json")); manifest=read(package/"manifest.json")
    least={"actions":["observe"],"credential_handles":[credential["handle"]],
           "network_origins":[boundary["route"]["authority"]],"write_prefixes":[]}
    if manifest.get("authority") != least or admission.get("package_digest") != digest:
        raise Refusal("requested authority is not the exact least grant")
    attachment={"schema":"aiko.adapter-attachment/v1","package_digest":digest,"authority":least,"active":True}
    atomic(attachments/"active.json",attachment); print(json.dumps(attachment,sort_keys=True))

def cmd_retry(a):
    _,package,receipts,registry,attachments=paths(a.work); digest=package_digest(package)
    attachment=read(attachments/"active.json")
    if not attachment.get("active") or attachment.get("package_digest") != digest: raise Refusal("adapter is not attached")
    result=invoke(a,package)
    if result.returncode: raise Refusal("real-path retry failed: "+result.stderr.strip())
    product=json.loads(result.stdout)
    atomic(receipts/"retry.json",{"schema":"aiko.adapter-retry/v1","package_digest":digest,
           "real_path":"unbrowse.execute","product":product,"passed":True})
    print(json.dumps(product,sort_keys=True))

def cmd_judge(a):
    boundary,credential=contracts(a.boundary,a.credential_contract)
    w,package,receipts,registry,attachments=paths(a.work); digest=package_digest(package)
    behavior=read(receipts/"behavior.json"); retry=read(receipts/"retry.json")
    admission=read(registry/(digest+".json")); attachment=read(attachments/"active.json")
    product=retry.get("product")
    good=(behavior.get("package_digest")==digest and admission.get("authority_granted") is False and
          attachment.get("package_digest")==digest and attachment.get("active") is True and
          retry.get("real_path")=="unbrowse.execute" and product=={"family":"worker-directory/v1","worker_ids":[a.expected_worker_id]})
    if not good: raise Refusal("independent judgment rejected authored adapter")
    evidence={"schema":"aiko.admitted-adapter-family/v1","family":"worker-directory/v1","package_digest":digest,
      "boundary_digest":sha(boundary),"credential_contract_digest":sha(credential),"written_inert":True,
      "behavior_tested_before_admission":True,"admitted_by_digest":True,"least_authority_attached":attachment["authority"],
      "real_path_retry":True,"judgment":"accepted","compilation_retains_nothing":True}
    atomic(w/"state"/"admitted-adapter-family.json",evidence); print(json.dumps(evidence,sort_keys=True))

def cmd_audit(a):
    audit_catalog(a.source); print(json.dumps({"catalogue":"bounded","gap_criteria_read":False}))

def parser():
    p=argparse.ArgumentParser(); s=p.add_subparsers(dest="command",required=True)
    q=s.add_parser("audit-catalog"); q.add_argument("--source"); q.set_defaults(fn=cmd_audit)
    q=s.add_parser("author"); q.add_argument("work"); q.add_argument("--boundary",required=True); q.add_argument("--credential-contract",required=True); q.set_defaults(fn=cmd_author)
    q=s.add_parser("compile"); q.add_argument("work"); q.set_defaults(fn=cmd_compile)
    for name,fn in (("test",cmd_test),("retry",cmd_retry)):
        q=s.add_parser(name); q.add_argument("work"); q.add_argument("--port",required=True); q.add_argument("--boundary-state",required=True); q.add_argument("--url",required=True); q.add_argument("--credential-env",required=True); q.add_argument("--expected-worker-id",type=int,required=True); q.set_defaults(fn=fn)
    q=s.add_parser("admit"); q.add_argument("work"); q.set_defaults(fn=cmd_admit)
    for name,fn in (("attach",cmd_attach),("judge",cmd_judge)):
        q=s.add_parser(name); q.add_argument("work"); q.add_argument("--boundary",required=True); q.add_argument("--credential-contract",required=True); q.add_argument("--expected-worker-id",type=int,default=7); q.set_defaults(fn=fn)
    return p

def main():
    a=parser().parse_args()
    try: a.fn(a)
    except Refusal as exc: print("refused: "+str(exc),file=sys.stderr); return 2
    return 0
if __name__=="__main__": raise SystemExit(main())